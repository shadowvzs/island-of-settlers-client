import { createWorkerJobQueue } from "../../../app/worker-job-queue";
import type { BuildingLevel } from "../../../render-common/buildings/levels/building-level";
import {
  hasLeveledRecipe, type LeveledRecipe, leveledRecipeKey, seedLeveledRecipe
} from "../../../render-common/buildings/levels/leveled-building-recipe";
import { buildingModelRecipe } from "../../../render-common/content/building-model-recipes";
import type { WorkerNation } from "../../../render-common/workers/worker-nation";
import { type PackedPartGroups, unpackPartGroups } from "./building-prepared-geometry";
import type { VariantRequest } from "./building-variant-builder";
import type { PreparedPartGroups } from "./roman-building";

/** One leveled recipe; `geometry` also asks for its merged part groups, `recipe` for the recipe itself. */
export type BuildingRecipeJob = {
  detailed: boolean; geometry: boolean; level: BuildingLevel; nation: WorkerNation; recipe: boolean; type: number
};
export type BuildingRecipeRequest = { jobs: BuildingRecipeJob[] };
export type BuildingRecipeEntry = { groups?: PackedPartGroups; key: string; leveled?: LeveledRecipe };
export type BuildingRecipeReply = { entries: BuildingRecipeEntry[]; error?: string; ms: number };

/** Load-time requests are split so two workers generate them in parallel. */
const LOAD_CHUNK = 8;
/** Prepared geometry waits for its build; abandoned sets (a building gone meanwhile) are dropped. */
const PREPARED_LIMIT = 12;

const createRecipeWorker = () =>
  new Worker(new URL("../../../workers/building-recipe-worker.ts", import.meta.url), { type: "module" });

const keyOf = (type: number, { level, nation }: VariantRequest, detailed: boolean) =>
  leveledRecipeKey(type, nation, level, detailed);

/** Neutral camps and authored models (the monuments of the settler-first nations) use no leveled recipe. */
const usesLeveledRecipe = (type: number, { level, nation, neutral }: VariantRequest) =>
  !neutral && buildingModelRecipe(type, nation, level).kind === "leveled";

/**
 * Both detail recipes of a player building: a simple model also reads its detailed recipe's stock
 * layout, and High parks the other recipe.
 */
export const recipeJobsOf = (type: number, request: VariantRequest): BuildingRecipeJob[] => {
  if (!usesLeveledRecipe(type, request)) return [];
  const { level, nation } = request;
  return [true, false].map(detailed => ({ detailed, geometry: false, level, nation, recipe: true, type }));
};

/**
 * Leveled recipes and merged model geometry generated by background workers. Recipes are adopted by
 * the recipe cache; prepared geometry waits until its model is built (once). A new or upgraded
 * building is built when both are ready, so this thread neither generates recipes nor merges parts.
 * Without worker support (tests, tools) or after a worker failure everything counts as ready and
 * the models are built synchronously, exactly as before.
 */
export const createBuildingRecipeJobs = (createWorker: (() => Worker) | undefined =
  typeof Worker === "undefined" ? undefined : createRecipeWorker) => {
  const pending = new Map<string, Promise<void>>();
  const prepared = new Map<string, PreparedPartGroups>();
  let failed = !createWorker;
  const queue = createWorker && createWorkerJobQueue<BuildingRecipeRequest, BuildingRecipeReply>({
    createWorker, onReply: () => undefined, size: 2, warmFirstWorker: import.meta.env.DEV
  });
  const adopt = (reply: BuildingRecipeReply) => {
    if (reply.error) throw new Error(reply.error);
    for (const { groups, key, leveled } of reply.entries) {
      if (leveled) seedLeveledRecipe(key, leveled);
      if (!groups) continue;
      prepared.delete(key);
      prepared.set(key, unpackPartGroups(groups));
      if (prepared.size > PREPARED_LIMIT) prepared.delete(prepared.keys().next().value!);
    }
  };
  const pendingKeys = (job: BuildingRecipeJob) => {
    const key = leveledRecipeKey(job.type, job.nation, job.level, job.detailed);
    return [job.recipe ? `recipe:${key}` : "", job.geometry ? `geometry:${key}` : ""].filter(Boolean);
  };
  const send = (jobs: BuildingRecipeJob[], urgent: boolean) => {
    const done = queue!.run<BuildingRecipeReply>({ jobs }, "building recipes", urgent).then(adopt)
      .catch((error: unknown) => {
        if (!failed) console.warn("Building recipe worker failed; buildings are built synchronously", error);
        failed = true;
      })
      .finally(() => { for (const key of jobs.flatMap(pendingKeys)) pending.delete(key); });
    for (const key of jobs.flatMap(pendingKeys)) pending.set(key, done);
  };
  /** Drops what is cached or already requested; a job left with nothing to do is skipped. */
  const missingOf = (job: BuildingRecipeJob): BuildingRecipeJob | undefined => {
    const key = leveledRecipeKey(job.type, job.nation, job.level, job.detailed);
    const recipe = job.recipe && !hasLeveledRecipe(key) && !pending.has(`recipe:${key}`);
    const geometry = job.geometry && !prepared.has(key) && !pending.has(`geometry:${key}`);
    return recipe || geometry ? { ...job, geometry, recipe } : undefined;
  };
  /** Starts the missing work (in chunks); resolves once every job is done. */
  const request = (jobs: readonly BuildingRecipeJob[], chunk: number, urgent: boolean) => {
    const missing = failed ? [] : jobs.flatMap(job => missingOf(job) ?? []);
    for (let start = 0; start < missing.length; start += chunk) send(missing.slice(start, start + chunk), urgent);
    return Promise.all(jobs.flatMap(pendingKeys).flatMap(key => pending.get(key) ?? [])).then(() => undefined);
  };
  /**
   * Whether the `detailed` model can be built now: both recipes cached and its geometry prepared.
   * Otherwise the missing work is requested (with the other recipe's geometry when it will be parked).
   */
  const ready = (type: number, variant: VariantRequest, detailed: boolean, parksOther: boolean) => {
    if (failed || !usesLeveledRecipe(type, variant)) return true;
    const recipes = [true, false].every(detail => hasLeveledRecipe(keyOf(type, variant, detail)));
    if (recipes && prepared.has(keyOf(type, variant, detailed))) return true;
    const jobs = recipeJobsOf(type, variant).map(job =>
      ({ ...job, geometry: job.detailed === detailed || parksOther }));
    void request(jobs, jobs.length, true);
    return false;
  };
  return {
    ready,
    /** The prepared geometry of one model build, or none (the model then merges its parts itself). */
    take: (type: number, variant: VariantRequest, detailed: boolean) => {
      if (!usesLeveledRecipe(type, variant)) return undefined;
      const key = keyOf(type, variant, detailed);
      const groups = prepared.get(key);
      prepared.delete(key);
      return groups;
    },
    /** Every recipe a loading island shows, generated in parallel chunks behind the loading screen. */
    prefetch: (jobs: readonly BuildingRecipeJob[]) => request(jobs, LOAD_CHUNK, false),
    dispose: () => {
      prepared.clear();
      queue?.disposeWhenIdle();
    }
  };
};
