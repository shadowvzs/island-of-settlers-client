import { type DataTexture, SRGBColorSpace } from "three";

import { inflateWithDecompressionStream, type Ktx2Rgba8Texture,
  parseKtx2Rgba8 } from "../../../render-common/baker/ktx2-rgba8";
import type { FoliageAtlasTile } from "../../../render-common/plants/foliage-atlas-layout";
import { createAtlasTexture } from "../three-materials";

/**
 * Runtime side of an offline decoration foliage atlas (D04a climbers, V-R02a verges). Loads the
 * processed KTX2 maps once per detail level, shares them between every user and frees them with
 * the last lease. No texture is painted at runtime; the mip chains are uploaded exactly as baked.
 *
 * Maps (all flipY = false, explicit coverage-preserving mips, LinearMipmapLinear filtering):
 * - `albedo` sRGB RGB + straight alpha coverage (cutoff 0.5, sharpen for alpha-to-coverage);
 * - `normal` tangent-space OpenGL normal (+v green), High only (null on Minimal);
 * - `orm` linear R = translucency, G = roughness, B = vertex-tint strength, A = 255 (reserved).
 */
export interface FoliageAtlasMaps {
  albedo: DataTexture;
  normal: DataTexture | null;
  orm: DataTexture;
}

export interface FoliageAtlasLease {
  maps: FoliageAtlasMaps;
  /** Idempotent; the maps are disposed when the last lease of their detail level is released. */
  release(): void;
  tiles: readonly FoliageAtlasTile[];
}

export type FoliageAtlasFetch = (url: string, file: string) => Promise<ArrayBuffer>;

type Detail = "high" | "minimal";

export type FoliageAtlasSources = Record<Detail, { albedo: URL; normal: URL | null; orm: URL }>;

/** Anisotropy per detail level (High 4, Minimal 1, as card D04b specifies). */
const ANISOTROPY: Record<Detail, number> = { high: 4, minimal: 1 };

const fetchArrayBuffer: FoliageAtlasFetch = async url => {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Foliage atlas ${url}: HTTP ${response.status}`);
  return response.arrayBuffer();
};

const fileName = (url: URL) => url.pathname.slice(url.pathname.lastIndexOf("/") + 1);

/** GPU texture of a parsed KTX2 file: its own mip chain, never regenerated by the driver. */
export const createFoliageAtlasTexture = (source: Ktx2Rgba8Texture, anisotropy: number) => {
  const texture = createAtlasTexture(source.levels[0]!.data, source.width, source.height, source.levels);
  texture.anisotropy = anisotropy;
  if (source.srgb) texture.colorSpace = SRGBColorSpace;
  return texture;
};

const loadTexture = async (url: URL, detail: Detail, fetchBytes: FoliageAtlasFetch) =>
  createFoliageAtlasTexture(await parseKtx2Rgba8(await fetchBytes(url.href, fileName(url)),
    inflateWithDecompressionStream), ANISOTROPY[detail]);

const loadMaps = async (sources: FoliageAtlasSources, detail: Detail,
  fetchBytes: FoliageAtlasFetch): Promise<FoliageAtlasMaps> => {
  const source = sources[detail];
  const [albedo, normal, orm] = await Promise.all([
    loadTexture(source.albedo, detail, fetchBytes),
    source.normal ? loadTexture(source.normal, detail, fetchBytes) : null,
    loadTexture(source.orm, detail, fetchBytes)
  ]);
  return { albedo, normal, orm };
};

const disposeMaps = (maps: FoliageAtlasMaps) => {
  maps.albedo.dispose();
  maps.normal?.dispose();
  maps.orm.dispose();
};

interface CacheEntry { maps: Promise<FoliageAtlasMaps>; users: number }

/** Shared, reference-counted maps of one atlas for High (`detailed`) or Minimal. */
export const createFoliageAtlasAcquirer = (sources: FoliageAtlasSources, tiles: readonly FoliageAtlasTile[]) => {
  const cache = new Map<Detail, CacheEntry>();
  const entryFor = (detail: Detail, fetchBytes: FoliageAtlasFetch) => {
    const cached = cache.get(detail);
    if (cached) return cached;
    const entry: CacheEntry = { maps: loadMaps(sources, detail, fetchBytes), users: 0 };
    cache.set(detail, entry);
    entry.maps.catch(() => { if (cache.get(detail) === entry) cache.delete(detail); });
    return entry;
  };
  return async (detailed: boolean, fetchBytes: FoliageAtlasFetch = fetchArrayBuffer): Promise<FoliageAtlasLease> => {
    const detail: Detail = detailed ? "high" : "minimal";
    const entry = entryFor(detail, fetchBytes);
    entry.users += 1;
    let maps: FoliageAtlasMaps;
    try {
      maps = await entry.maps;
    } catch (error) {
      entry.users -= 1;
      throw error;
    }
    let released = false;
    return {
      maps,
      release: () => {
        if (released) return;
        released = true;
        entry.users -= 1;
        if (entry.users > 0 || cache.get(detail) !== entry) return;
        cache.delete(detail);
        disposeMaps(maps);
      },
      tiles
    };
  };
};
