import { mkdirSync, writeFileSync } from "node:fs";
import { ShapeGeometry, ShapePath } from "three";

import sharp from "../../../island-of-settlers-asset-tools/node_modules/sharp/dist/index.mjs";
import { simplifyGlyphContour } from "./simplify-glyph-contour";

const SIZE = 160;
const characters = ["福", "安", "吉", "祥", "春", "喜"];
const triangles: number[][] = [];
const output = process.argv[2] ?? "../resources/project-reviews/hq-owner-rejection-2026-11-03/glyph-vectors-b";
mkdirSync(output, { recursive: true });
for (const character of characters) {
  // Only the font's rendered outline is derived; font binaries are not bundled into the game.
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}">` +
    `<text x="80" y="135" text-anchor="middle" font-family="Droid Sans Fallback" ` +
    `font-size="140" fill="white">${character}</text></svg>`;
  const png = await sharp(Buffer.from(svg)).png().toBuffer();
  await sharp(png).toFile(`${output}/glyph-${character}.png`);
  const { data, info } = await sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const ink = (x: number, y: number) => x >= 0 && y >= 0 && x < SIZE && y < SIZE &&
    data[(y * SIZE + x) * info.channels + 3]! >= 128;
  type Point = readonly [number, number];
  const edges = new Map<string, Point[]>();
  const key = (point: Point) => `${point[0]},${point[1]}`;
  const edge = (from: Point, to: Point) => {
    const list = edges.get(key(from)) ?? []; list.push(to); edges.set(key(from), list);
  };
  for (let y = 0; y < SIZE; y++) for (let x = 0; x < SIZE; x++) {
    if (!ink(x, y)) continue;
    if (!ink(x, y - 1)) edge([x, y], [x + 1, y]);
    if (!ink(x + 1, y)) edge([x + 1, y], [x + 1, y + 1]);
    if (!ink(x, y + 1)) edge([x + 1, y + 1], [x, y + 1]);
    if (!ink(x - 1, y)) edge([x, y + 1], [x, y]);
  }
  const path = new ShapePath();
  while (edges.size) {
    const start = edges.keys().next().value!;
    let position = start;
    const points: Point[] = [];
    do {
      const [x, y] = position.split(",").map(Number);
      points.push([x!, SIZE - y!]);
      const list = edges.get(position);
      if (!list?.length) throw new Error(`Unclosed ${character} contour`);
      const next = list.pop()!;
      if (!list.length) edges.delete(position);
      position = key(next);
    } while (position !== start);
    const corners = points.filter((point, index) => {
      const before = points[(index + points.length - 1) % points.length]!;
      const after = points[(index + 1) % points.length]!;
      return (point[0] - before[0]) * (after[1] - point[1]) !==
        (point[1] - before[1]) * (after[0] - point[0]);
    });
    const contour = simplifyGlyphContour(corners);
    if (contour.length < 3) continue;
    path.moveTo(...contour[0]!);
    for (const point of contour.slice(1)) path.lineTo(...point);
    path.currentPath!.closePath();
  }
  const indexed = new ShapeGeometry(path.toShapes());
  indexed.computeBoundingBox();
  const bounds = indexed.boundingBox!, width = bounds.max.x - bounds.min.x, height = bounds.max.y - bounds.min.y;
  if (!(width > 20 && height > 20)) throw new Error(`Missing Chinese glyph ${character}`);
  const geometry = indexed.toNonIndexed(), positions = geometry.getAttribute("position");
  const points: number[] = [];
  for (let index = 0; index < positions.count; index++) points.push(
    Number(((positions.getX(index) - bounds.min.x) / width - .5).toFixed(5)),
    Number(((positions.getY(index) - bounds.min.y) / height).toFixed(5)));
  indexed.dispose(); geometry.dispose(); triangles.push(points);
}
writeFileSync("src/render-common/props/chinese-lantern-glyphs.ts",
  "/** Generated by tools/assets/chinese-lantern-glyphs.ts from Droid Sans Fallback (Apache-2.0).\n" +
  " * Copyright 2006–2010 Google Corp.; license/source receipt: resources/project-reviews/chinese-hq-2026-11-03. */\n" +
  `export const CHINESE_LANTERN_CHARACTERS = ${JSON.stringify(characters)} as const;\n` +
  `export const CHINESE_LANTERN_GLYPHS: readonly (readonly number[])[] = ${JSON.stringify(triangles)};\n`);
console.log(JSON.stringify(characters.map((character, index) => ({ character, triangles: triangles[index]!.length / 6 }))));
