import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { gzipSync } from "node:zlib";

import { createServer } from "vite";

/**
 * Evaluates every building recipe once and writes the gameplay geometry sidecars (catalog README, "Building
 * geometry"): `data/buildings/<key>/geometry.json` (plot, door, entrance sweep, logistics, worker exit, mechanism;
 * nation independent) and `data/buildings/<key>/navigation/<nation>.json` (rooms, obstacles and stock displays per
 * level; a nation whose walkable area equals the Roman one reuses the Roman file), plus the two index modules.
 * Run after building model changes: npm run building-geometry (part of npm run building-assets).
 * `--measure` prints sizes and the nations with their own walkable area, without writing.
 */
const DATA = resolve(import.meta.dirname, "../../../island-of-settlers-shared/src/catalog/data/buildings");
const LEVELS = [1, 2, 3, 4, 5] as const;
const BASE_NATION = "roman";
const measureOnly = process.argv.includes("--measure");

const sizes = { geometry: 0, navigation: 0, navigationGzip: 0, navigationFiles: 0 };
const write = (file: string, text: string) => {
  if (!measureOnly) writeFileSync(file, text);
};

/** Two-space JSON with number lists (points, cells) kept on one line. */
const prettyJson = (value: unknown) => `${JSON.stringify(value, null, 2)
  .replace(/\[\s+(-?[\d.e+-]+(?:,\s+-?[\d.e+-]+)*)\s+\]/g,
    (_, list: string) => `[${list.split(/,\s+/).join(", ")}]`)}\n`;

/** Levels 1-5; a level equal to an earlier one is stored as that level's number. */
const dedupedLevels = (levels: readonly unknown[]) => {
  const texts = levels.map(level => JSON.stringify(level));
  return levels.map((level, index) => {
    const same = texts.indexOf(texts[index]!);
    return same < index ? same + 1 : level;
  });
};

const geometryIndex = (keys: readonly string[]) => [
  ...keys.map(key => `import ${key} from "./${key}/geometry.json" with { type: "json" };`), "",
  "/** Generated by `npm run building-geometry`: every active building's geometry sidecar. */",
  "export const BUILDING_GEOMETRY_FILES = {", ...keys.map(key => `  ${key},`), "};", ""
].join("\n").replace(",\n};", "\n};");

const navigationIndex = (files: Readonly<Record<string, Readonly<Record<string, string>>>>) => [
  "/**",
  " * Generated by `npm run building-geometry`: lazy importers of every building's navigation sidecar per nation",
  " * (a nation with the Roman walkable area imports the Roman file).",
  " */",
  "export const BUILDING_NAVIGATION_FILES: Readonly<Record<string, Readonly<Record<string, () => Promise<unknown>>>>> = {",
  ...Object.entries(files).map(([key, byNation]) => [`  ${key}: {`, ...Object.entries(byNation).map(([nation, file]) =>
    `    ${nation}: () => import("./${key}/navigation/${file}.json", { with: { type: "json" } }),`), "  },"]
    .join("\n")),
  "};", ""
].join("\n");

const server = await createServer({
  appType: "custom", logLevel: "error", server: { hmr: false, middlewareMode: true }
});
try {
  const load = (path: string) => server.ssrLoadModule(path);
  const { buildingEntry } = await load("@shared/catalog");
  const { BUILDING_CATALOG } = await load("/src/render-common/buildings/building-catalog.ts");
  const { PLAYER_NATIONS } = await load("/src/render-common/workers/worker-appearance.ts");
  const reference = await load("/src/render-common/buildings/building-geometry-reference.ts");
  const ownWalkableArea: Record<string, string[]> = {};
  const navigationFiles: Record<string, Record<string, string>> = {};
  const started = performance.now();
  for (const definition of BUILDING_CATALOG) {
    const key = buildingEntry(definition.id).key as string;
    const folder = join(DATA, key, "navigation");
    if (!measureOnly) {
      mkdirSync(folder, { recursive: true });
      for (const file of readdirSync(folder)) rmSync(join(folder, file));
    }
    const geometry = prettyJson(reference.computeBuildingGeometry(definition));
    sizes.geometry += geometry.length;
    write(join(DATA, key, "geometry.json"), geometry);
    let base = "";
    ownWalkableArea[key] = [];
    navigationFiles[key] = {};
    for (const nation of PLAYER_NATIONS as readonly string[]) {
      const levels = LEVELS.map(level => reference.computeBuildingNavigationLevel(definition.id, nation, level));
      const text = `${JSON.stringify({ levels: dedupedLevels(levels) })}\n`;
      if (nation === BASE_NATION) base = text;
      const file = nation !== BASE_NATION && text === base ? BASE_NATION : nation;
      navigationFiles[key][nation] = file;
      if (file !== nation) continue;
      if (nation !== BASE_NATION) ownWalkableArea[key].push(nation);
      sizes.navigation += text.length;
      sizes.navigationGzip += gzipSync(text).length;
      sizes.navigationFiles++;
      write(join(folder, `${nation}.json`), text);
    }
  }
  const keys = Object.keys(navigationFiles).sort();
  write(join(DATA, "geometry-index.ts"), geometryIndex(keys));
  write(join(DATA, "navigation-index.ts"), navigationIndex(Object.fromEntries(keys.map(key =>
    [key, navigationFiles[key]!]))));
  const seconds = ((performance.now() - started) / 1000).toFixed(1);
  console.log(JSON.stringify({ seconds, sizes, ownWalkableArea }));
} finally {
  await server.close();
}
