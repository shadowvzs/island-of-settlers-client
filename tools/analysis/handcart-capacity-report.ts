import { writeFile } from "node:fs/promises";

import { CART_CARGO_LAYOUTS } from "../../src/render-common/logistics/cart-cargo-layouts";
import {
  CART_EXCLUDED_WARES, cartCapacityFor,
HANDCART} from "../../src/render-common/logistics/handcart-rules";
import { WARE_IDS } from "../../src/render-common/wares/ware-catalog";
import { maximumTalentModifier } from "../../src/shared/progression/talents";

/**
 * Writes the audited per-ware hand-cart capacity. Capacity is an item count taken from the packed
 * model layout (not a volume estimate); the talent raises it and the save validator uses the same
 * maximum. Usage: tsx tools/analysis/handcart-capacity-report.ts [output.md]
 */
const output = process.argv[2];
const talent = maximumTalentModifier("handcartCapacity");
const missing = WARE_IDS.filter(ware => !CART_EXCLUDED_WARES.has(ware) && !(ware in CART_CARGO_LAYOUTS));
if (missing.length) throw new Error(`Cart-eligible wares without a layout: ${missing.join(", ")}`);
const rows = WARE_IDS.map(ware => {
  if (CART_EXCLUDED_WARES.has(ware))
    return `| ${ware} | excluded | 0 | 0 |`;
  const layout = CART_CARGO_LAYOUTS[ware as keyof typeof CART_CARGO_LAYOUTS];
  return `| ${ware} | ${layout.count} | ${cartCapacityFor(ware)} | ${cartCapacityFor(ware, talent)} |`;
});
const document = `# Hand-cart capacity — current rule

Generated by \`island-of-settlers-client/tools/analysis/handcart-capacity-report.ts\` on 2026-10-23. The cart bed is
${HANDCART.load} load units, ${HANDCART.maxItems} item slots, and every ware uses the layout packed
from both model LODs.

**Rule:** capacity is an **item count**, derived from the audited visual layout — not a modelled
volume. A ware with a 6-item layout carries 6 items; coal/ore layouts carry 4 because their models
pack four per bed. Mixed cargo must also fit the separate ${HANDCART.load}-unit weight budget in
\`cartLoadFits\` (for example, six logs plus one fish does not fit). Tools use their audited layout,
not a separate tool capacity.

The handcart talent raises the count by \`floor(base × (1 + bonus))\`; the maximum talent bonus is
${talent}, so the save validator accepts up to the "max talent" column. The cart drawing keeps the
base layout and adds heaped slots for a talent-raised load; the UI heap variant uses the same
\`cartCapacityFor\` call.

| Ware | Layout count | Base capacity | Max talent |
| --- | ---: | ---: | ---: |
${rows.join("\n")}
`;
if (output) await writeFile(output, document);
console.log(document);
