import { writeFile } from "node:fs/promises";

import { d6CorridorHotspotSave } from "../../tests/helpers/d6-corridor-fixture";

/**
 * Writes the frozen D6 straight-corridor hotspot used by the experiment benchmark.
 * Usage: tsx tools/analysis/d6-corridor-fixture.ts [output.json]
 */
const output = process.argv[2] ?? "../resources/offline-cost-current/d6/corridor-hotspot.json";
const save = await d6CorridorHotspotSave();
await writeFile(output, JSON.stringify(save));
console.log(JSON.stringify({
  output, savedAt: save.savedAt, buildings: save.settlement.buildings.length,
  actors: save.settlement.actors.length,
  note: "Generated by the real simulation; use the SHA-256 in the experiment doc."
}));
